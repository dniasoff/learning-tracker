import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const source = join(root, 'assets', 'content', 'hierarchy');
const target = join(root, 'functions', 'src', 'group_curriculum_manifest.ts');
const supported = new Set(['bavli', 'chumash', 'mishna_berurah', 'mishnayos', 'mishneh_torah', 'mussar', 'nach', 'yerushalmi']);
const files = (await readdir(source)).filter((name) => name.endsWith('.json') && supported.has(name.slice(0, -5))).sort();
const rows = [];

for (const file of files) {
  const { items, hierarchyConfig } = JSON.parse(await readFile(join(source, file), 'utf8'));
  const sorted = items.filter((item) => item.curriculumId && item.sefariaRef)
    .sort((a, b) => a.sortOrder - b.sortOrder);
  const pathOf = (item) => [item.level1, item.level2, item.level3, item.level4].filter((part) => part !== undefined);
  const pathKey = (curriculumId, path) => JSON.stringify([curriculumId, path]);
  const nonLeavesByPath = new Map(sorted.filter((item) => !item.isLeaf)
    .map((item) => [pathKey(item.curriculumId, pathOf(item)), item]));
  const leaves = sorted.filter((item) => item.isLeaf).map((item) => ({
    curriculumId: item.curriculumId,
    path: pathOf(item),
  }));
  const leafCounts = new Map();
  for (const leaf of leaves) {
    for (let depth = 1; depth <= leaf.path.length; depth++) {
      const key = pathKey(leaf.curriculumId, leaf.path.slice(0, depth));
      leafCounts.set(key, (leafCounts.get(key) ?? 0) + 1);
    }
  }
  for (const item of sorted.filter((entry) => !entry.isLeaf && entry.level4 === undefined)) {
    const path = pathOf(item);
    const weight = leafCounts.get(pathKey(item.curriculumId, path)) ?? 0;
    if (weight < 1) continue;
    rows.push({
      curriculumId: item.curriculumId,
      ref: item.sefariaRef,
      label: item.displayNameEn ?? item.sefariaRef,
      level: hierarchyConfig.levelLabels[path.length - 1]?.toLowerCase() ?? `level${path.length}`,
      depth: path.length,
      sortOrder: item.sortOrder,
      parentRef: path.length === 1 ? null : nonLeavesByPath.get(pathKey(item.curriculumId, path.slice(0, -1)))?.sefariaRef ?? null,
      weight,
    });
  }
  for (const item of sorted.filter((entry) => entry.isLeaf)) {
    const path = pathOf(item);
    const parent = nonLeavesByPath.get(pathKey(item.curriculumId, path.slice(0, -1)));
    rows.push({
      curriculumId: item.curriculumId,
      ref: item.sefariaRef,
      label: item.displayNameEn ?? item.sefariaRef,
      level: hierarchyConfig.levelLabels[path.length - 1]?.toLowerCase() ?? `level${path.length}`,
      depth: path.length,
      sortOrder: item.sortOrder,
      parentRef: parent?.sefariaRef ?? null,
      weight: 1,
    });
  }
}

rows.sort((a, b) => a.curriculumId.localeCompare(b.curriculumId) || a.sortOrder - b.sortOrder);

// Tanach is composed from the canonical Chumash and Nach trees. Normalize
// both into a shared Chumash/Nach -> sefer -> perek shape so the allocator
// can treat each sefer as a whole unit and split at perakim when needed.
const tanach = [];
for (const category of [
  { id: 'chumash', ref: 'Chumash', sourceDepth: 1, categoryDepth: 1 },
  { id: 'nach', ref: 'Nach', sourceDepth: 2, categoryDepth: 1 },
]) {
  const sourceRows = rows.filter((row) => row.curriculumId === category.id);
  const sefarim = sourceRows.filter((row) => row.depth === category.sourceDepth);
  tanach.push({ curriculumId: 'tanach', ref: category.ref, label: category.ref, level: 'section', depth: 1,
    parentRef: null, weight: sefarim.reduce((sum, row) => sum + row.weight, 0), sortOrder: category.id === 'chumash' ? 0 : 1 });
  for (const sefer of sefarim) {
    const parentRef = category.ref;
    tanach.push({ ...sefer, curriculumId: 'tanach', depth: 2, parentRef,
      sortOrder: (category.id === 'chumash' ? 0 : 100) + sefer.sortOrder });
    for (const child of sourceRows.filter((row) => row.parentRef === sefer.ref && row.depth === category.sourceDepth + 1)) {
      tanach.push({ ...child, curriculumId: 'tanach', depth: 3, parentRef: sefer.ref,
        sortOrder: (category.id === 'chumash' ? 0 : 100) + child.sortOrder });
    }
  }
}
rows.push(...tanach);
rows.sort((a, b) => a.curriculumId.localeCompare(b.curriculumId) || a.sortOrder - b.sortOrder);
const body = `// Generated by tools/generate_group_curriculum_manifest.mjs from assets/content/hierarchy.\n` +
  `// Do not edit manually. It contains canonical non-leaf scope units and leaf counts.\n` +
  `export interface GroupCurriculumNodeData { curriculumId: string; ref: string; label: string; level: string; depth: number; parentRef: string | null; weight: number; sortOrder: number; }\n` +
  `export const GROUP_CURRICULUM_NODES: readonly GroupCurriculumNodeData[] = ${JSON.stringify(rows)};\n`;
await writeFile(target, body);
console.log(`Generated ${rows.length} canonical group scope nodes.`);
